#!/usr/bin/env python3
"""Generates lib/l10n/en_dictionary.dart from:
   ar_strings.json (keys extracted from the ORIGINAL source) + en_all.txt (idx => English)
   + extra_en.txt (new strings: 'Arabic => English')."""
import json,re,sys
import os
W=os.path.dirname(os.path.abspath(__file__))+'/'
keys=json.load(open(W+'ar_strings.json',encoding='utf-8'))
en={}
for line in open(W+'en_all.txt',encoding='utf-8'):
    line=line.rstrip('\n')
    if line.strip():
        i,e=line.split(' => ',1); en[keys[int(i)]]=e
for line in open(W+'extra_en.txt',encoding='utf-8'):
    line=line.rstrip('\n')
    if line.strip() and not line.startswith('#'):
        a,e=line.split(' => ',1); en[a]=e
PH=re.compile(r'(?<!\\)\$\{[^}]*\}|(?<!\\)\$[A-Za-z_]\w*')
def unesc(s):
    out=[];i=0
    while i<len(s):
        c=s[i]
        if c=='\\' and i+1<len(s):
            n=s[i+1]; out.append({'n':'\n','t':'\t'}.get(n,n)); i+=2
        else: out.append(c); i+=1
    return ''.join(out)
def rx_escape(s): return re.sub(r'([\\^$.|?*+()\[\]{}])',r'\\\1',s)
def dq(s): return "'"+s.replace('\\','\\\\').replace("'","\\'").replace('$','\\$').replace('\n','\\n')+"'"
exact={};tpl=[]
for k,v in en.items():
    v=unesc(v) if '\\n' in v else v
    if PH.search(k):
        parts=PH.split(k); n=len(PH.findall(k))
        assert v.count('{}')==n,(k,v)
        rx='^'+'(.+?)'.join(rx_escape(unesc(p)) for p in parts)+'$'
        tpl.append((rx,v))
    else:
        exact[unesc(k)]=v
# longer / more specific templates first
tpl.sort(key=lambda t:-len(t[0]))
out=["// GENERATED by tools/gen_dict.py — do not edit by hand.",
     "// Arabic (source language of the app) -> English.","",
     "const Map<String, String> kEn = <String, String>{"]
for k in sorted(exact): out.append(f"  {dq(k)}: {dq(exact[k])},")
out+=["};","","/// [regex, english-with-{}] — each {} is a captured, recursively translated value.",
      "const List<List<String>> kEnTemplates = <List<String>>["]
for rx,v in tpl: out.append(f"  [{dq(rx)}, {dq(v)}],")
out.append("];")
open(W+'../lib/l10n/en_dictionary.dart','w',encoding='utf-8').write('\n'.join(out)+'\n')
print('exact',len(exact),'templates',len(tpl))
